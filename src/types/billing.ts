/**
 * ---------------------------------------------------------------------------
 * SECTION 06 — BILLING & PAYMENTS TYPES
 * ---------------------------------------------------------------------------
 * Frontend-only: every shape below describes LOCAL DEMO data held in React
 * state. No payment gateway, API, database or real transaction backs any of
 * it. Students pay PG owners directly (UPI / cash / bank transfer offline)
 * and the owner records the receipt manually — RahoMitra never collects rent.
 * ---------------------------------------------------------------------------
 */

/** Payment statuses shown across owner + student billing screens. */
export type BillStatus = 'DRAFT' | 'UNPAID' | 'PARTIALLY_PAID' | 'PAID' | 'OVERDUE'

/** Offline payment methods an owner can record manually. */
export type PaymentMethod = 'UPI' | 'CASH' | 'BANK_TRANSFER' | 'OTHER'

/** A monthly rent bill generated by the PG owner. */
export interface RentBill {
  id: string
  propertyId: string
  studentId: string
  /** Denormalised for table rendering — matches OwnerStudent.name. */
  studentName: string
  roomId: string
  roomNumber: string
  bedLabel: string
  /** Billing month (ISO yyyy-mm) — the month the rent is for. */
  month: string
  rent: number
  electricity: number
  water: number
  maintenance: number
  food: number
  extra: number
  discount: number
  /** Payment due date — 5th of the month after the billing month. */
  dueDate: string
  notes: string
  /** Draft bills are owner-only and never shown in the student portal. */
  draft: boolean
  paidAmount: number
  generatedOn: string
}

/** A payment the owner manually recorded against a bill. */
export interface PaymentRecord {
  id: string
  billId: string
  propertyId: string
  studentId: string
  studentName: string
  amount: number
  method: PaymentMethod
  /** Optional UPI / NEFT reference typed by the owner (demo). */
  reference: string
  /** Date the money was actually received (yyyy-mm-dd). */
  date: string
  notes: string
  recordedOn: string
}

/** Owner payment instructions shown to students on their invoices. */
export interface PaymentDetails {
  upiId: string
  accountHolder: string
  instructions: string
  /** Local data-URL preview only — never uploaded anywhere. */
  qrImage: string
}

/** Payload used to generate or edit a bill. */
export interface BillInput {
  propertyId: string
  studentId: string
  month: string
  rent: number
  electricity: number
  water: number
  maintenance: number
  food: number
  extra: number
  discount: number
  dueDate: string
  notes: string
}

/** Payload for a manually recorded payment. */
export interface PaymentInput {
  billId: string
  amount: number
  method: PaymentMethod
  reference: string
  date: string
  notes: string
}

/* ------------------------------------------------------------- calculations */

/** Subtotal = rent + every charge. */
export function billSubtotal(bill: Pick<BillInput, 'rent' | 'electricity' | 'water' | 'maintenance' | 'food' | 'extra'>): number {
  return bill.rent + bill.electricity + bill.water + bill.maintenance + bill.food + bill.extra
}

/** Final amount = subtotal − discount (never below zero). */
export function billTotal(
  bill: Pick<BillInput, 'rent' | 'electricity' | 'water' | 'maintenance' | 'food' | 'extra' | 'discount'>,
): number {
  return Math.max(0, billSubtotal(bill) - bill.discount)
}

/** Amount still outstanding on a bill. */
export function billRemaining(bill: RentBill): number {
  return Math.max(0, billTotal(bill) - bill.paidAmount)
}

/**
 * Derived status — a bill is only ever PAID/PARTIALLY_PAID when real demo
 * payments were recorded against it, and OVERDUE only after its due date.
 */
export function billStatus(bill: RentBill, today: string): BillStatus {
  if (bill.draft) return 'DRAFT'
  const total = billTotal(bill)
  if (bill.paidAmount >= total && total > 0) return 'PAID'
  if (bill.paidAmount > 0) return 'PARTIALLY_PAID'
  if (bill.dueDate < today) return 'OVERDUE'
  return 'UNPAID'
}

