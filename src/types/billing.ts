/* ------------------------------------------------------------ date helpers */

const MONTH_NAMES = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec']

/** '2026-05' → 'May 2026' */
export function monthLabel(month: string): string {
  const [y, m] = month.split('-').map(Number)
  if (!y || !m) return month
  return `${MONTH_NAMES[m - 1]} ${y}`
}

/** '2026-05' → '1 – 31 May 2026' */
export function billingPeriod(month: string): string {
  const [y, m] = month.split('-').map(Number)
  if (!y || !m) return month
  const days = new Date(Date.UTC(y, m, 0)).getUTCDate()
  return `1 – ${days} ${MONTH_NAMES[m - 1]} ${y}`
}

/** '2026-06-05' → '5 Jun 2026' */
export function formatDate(iso: string): string {
  const [y, m, d] = iso.split('-').map(Number)
  if (!y || !m || !d) return iso
  return `${d} ${MONTH_NAMES[m - 1]} ${y}`
}

/** Payment due date for a billing month: 5th of the following month. */
export function dueDateFor(month: string): string {
  const [y, m] = month.split('-').map(Number)
  if (!y || !m) return ''
  return new Date(Date.UTC(y, m, 5)).toISOString().slice(0, 10)
}
